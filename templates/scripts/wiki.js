#!/usr/bin/env node
'use strict';

// Screen / feature wiki bookkeeping (docs/wiki). The orchestrator writes the
// pages; this script does the parts that must not be guessed: page status,
// source hashes, the index and field search.
//
//   node wiki.js check [--json] [--strict] [--root <dir>]
//   node wiki.js stamp <slug>… | --all     [--root <dir>]
//   node wiki.js index                     [--root <dir>]
//   node wiki.js find <term> [--json]      [--root <dir>]
//
// Pages: <root>/docs/wiki/screens/<slug>.md (kind: screen) and
// <root>/docs/wiki/features/<slug>.md (kind: feature). The frontmatter is a
// small YAML subset: `key: value` and `key: [a, b]` lines between `---` fences.
// Status (first match): invalid · broken · unstamped · stale · ok.
// Writes only `.md` files inside <root>/docs/wiki: stamp rewrites the two
// lines source_hash / stamped_at of a page; index rewrites index.md.
// Exit 0 = done, 1 = error (or --strict with a page that is not ok), 2 = refused / usage.

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { parseArgs } = require('./jev-client');

class Refused extends Error {}

const KINDS = { screens: 'screen', features: 'feature' };
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const KEY_RE = /^[a-z_]+$/;
const LIST_KEYS = ['files', 'components', 'apis', 'states', 'links_to', 'screens'];
const TEXT_KEYS = ['kind', 'slug', 'title', 'route', 'tc', 'source_hash', 'stamped_at'];
const STAMP_KEYS = ['source_hash', 'stamped_at'];
const REQUIRED = { screen: ['kind', 'slug', 'title', 'route', 'files'], feature: ['kind', 'slug', 'title', 'screens'] };
const NOT_FOR = { screen: ['screens'], feature: ['route', 'components', 'states', 'links_to'] };
const FIND_FIELDS = ['slug', 'title', 'route', 'files', 'components', 'apis', 'states'];
const MAX_LIST = 200;
const MAX_TEXT = 300;
const MAX_PAGE_BYTES = 256 * 1024;
const ORDER = ['invalid', 'broken', 'unstamped', 'stale', 'ok'];
const INDEX_HEADER = '<!-- generated by wiki.js index — do not edit; run `node ~/.claude/scripts/wiki.js index` -->';

const sha256 = s => crypto.createHash('sha256').update(s).digest('hex');

// ── frontmatter ──────────────────────────────────────────────────────────

function unquote(v) {
  if (v.length >= 2 && ((v[0] === '"' && v.endsWith('"')) || (v[0] === "'" && v.endsWith("'")))) return v.slice(1, -1);
  return v;
}

// Returns { data, fmEnd, lines, errors }. fmEnd = index of the closing fence line.
function parseFrontmatter(text) {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const errors = [];
  const data = Object.create(null);
  if (lines[0] !== '---') return { data, fmEnd: -1, lines, errors: ['no frontmatter (the first line must be ---)'] };
  const fmEnd = lines.indexOf('---', 1);
  if (fmEnd < 0) return { data, fmEnd: -1, lines, errors: ['frontmatter is not closed with ---'] };
  for (let i = 1; i < fmEnd; i++) {
    const line = lines[i];
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const m = /^([^:\s]+):[ \t]*(.*)$/.exec(line);
    if (!m) { errors.push(`line ${i + 1}: not a "key: value" line`); continue; }
    const key = m[1];
    const raw = m[2].trim();
    if (!KEY_RE.test(key)) { errors.push(`line ${i + 1}: bad key ${JSON.stringify(key)}`); continue; }
    if (key in data) { errors.push(`duplicate key ${key}`); continue; }
    if (raw.startsWith('[')) {
      if (!raw.endsWith(']')) { errors.push(`${key}: list is not closed with ]`); continue; }
      const inner = raw.slice(1, -1).trim();
      data[key] = inner ? inner.split(',').map(s => unquote(s.trim())) : [];
    } else {
      data[key] = unquote(raw);
    }
  }
  return { data, fmEnd, lines, errors };
}

// ── project / wiki location ──────────────────────────────────────────────

function isLink(p) {
  try { return fs.lstatSync(p).isSymbolicLink(); } catch { return false; }
}

function locate(rootArg) {
  let root;
  try { root = fs.realpathSync(path.resolve(rootArg || process.cwd())); } catch (e) { throw new Refused(`root ${rootArg}: ${e.code || e.message}`); }
  const docs = path.join(root, 'docs');
  const wiki = path.join(docs, 'wiki');
  for (const p of [docs, wiki]) if (isLink(p)) throw new Refused(`${path.relative(root, p)} must not be a symlink`);
  const exists = fs.existsSync(wiki);
  if (exists) {
    if (!fs.statSync(wiki).isDirectory()) throw new Refused('docs/wiki must be a directory');
    if (fs.realpathSync(wiki) !== wiki) throw new Refused('docs/wiki must not resolve outside the project');
  }
  return { root, wiki, exists };
}

// Resolve a page's `files` entry; returns { real } or { problem }.
function resolveFile(root, rel) {
  if (typeof rel !== 'string' || !rel) return { problem: 'empty file entry' };
  if (path.isAbsolute(rel) || rel.includes('\0')) return { problem: `${rel}: must be a path relative to the project` };
  const abs = path.resolve(root, rel);
  if (!abs.startsWith(root + path.sep)) return { problem: `${rel}: outside the project` };
  let real;
  try { real = fs.realpathSync(abs); } catch { return { problem: `${rel}: missing` }; }
  if (!real.startsWith(root + path.sep)) return { problem: `${rel}: resolves outside the project` };
  if (!fs.statSync(real).isFile()) return { problem: `${rel}: not a file` };
  return { real };
}

function sourceHash(root, files) {
  const rows = [...files].sort().map(rel => {
    const r = resolveFile(root, rel);
    if (r.problem) throw new Refused(r.problem);
    return `${rel}\0${sha256(fs.readFileSync(r.real, 'utf8').replace(/\r\n/g, '\n'))}\n`;
  });
  return sha256(rows.join('')).slice(0, 16);
}

// ── pages ────────────────────────────────────────────────────────────────

function validate(page) {
  const d = page.data;
  const errs = [];
  for (const k of Object.keys(d)) {
    if (!LIST_KEYS.includes(k) && !TEXT_KEYS.includes(k)) errs.push(`unknown key ${k}`);
    else if (LIST_KEYS.includes(k)) {
      if (!Array.isArray(d[k])) errs.push(`${k} must be a list [a, b]`);
      else if (d[k].length > MAX_LIST) errs.push(`${k} has more than ${MAX_LIST} entries`);
      else if (d[k].some(v => !v)) errs.push(`${k} has an empty entry`);
    } else if (Array.isArray(d[k])) errs.push(`${k} must be a single value`);
    else if (d[k].length > MAX_TEXT) errs.push(`${k} is longer than ${MAX_TEXT} characters`);
  }
  const kind = d.kind;
  if (!kind) errs.push('missing kind');
  else if (kind !== page.dirKind) errs.push(`kind ${kind} does not match the directory (${page.dirKind})`);
  else {
    for (const k of REQUIRED[kind]) if (k !== 'kind' && (d[k] === undefined || d[k] === '' || (Array.isArray(d[k]) && !d[k].length))) errs.push(`missing ${k}`);
    for (const k of NOT_FOR[kind]) if (k in d) errs.push(`${k} is not used on a ${kind} page`);
  }
  if (d.slug !== undefined && !Array.isArray(d.slug)) {
    if (!SLUG_RE.test(d.slug)) errs.push(`slug ${d.slug} is not kebab-case`);
    else if (d.slug !== page.fileSlug) errs.push(`slug ${d.slug} does not match the file name ${page.fileSlug}.md`);
  }
  return errs;
}

function loadPages(loc) {
  const pages = [];
  if (!loc.exists) return pages;
  for (const [dir, dirKind] of Object.entries(KINDS)) {
    const full = path.join(loc.wiki, dir);
    if (!fs.existsSync(full)) continue;
    if (isLink(full) || !fs.statSync(full).isDirectory()) throw new Refused(`docs/wiki/${dir} must be a directory, not a symlink`);
    for (const name of fs.readdirSync(full).sort()) {
      if (!name.endsWith('.md')) continue;
      const file = path.join(full, name);
      const page = { file, rel: path.relative(loc.root, file), dirKind, fileSlug: name.slice(0, -3), errors: [], data: Object.create(null) };
      if (isLink(file)) page.errors.push('page must not be a symlink');
      else if (fs.statSync(file).size > MAX_PAGE_BYTES) page.errors.push(`page is larger than ${MAX_PAGE_BYTES} bytes`);
      else {
        const fm = parseFrontmatter(fs.readFileSync(file, 'utf8'));
        page.data = fm.data;
        page.errors.push(...fm.errors);
        if (!fm.errors.length) page.errors.push(...validate(page));
      }
      page.slug = page.fileSlug;
      pages.push(page);
    }
  }
  const seen = new Map();
  for (const p of pages) {
    if (seen.has(p.slug)) {
      const msg = `slug ${p.slug} is used by both ${seen.get(p.slug).rel} and ${p.rel}`;
      p.errors.push(msg);
      seen.get(p.slug).errors.push(msg);
    } else seen.set(p.slug, p);
  }
  return pages;
}

function statusOf(loc, page, bySlug) {
  if (page.errors.length) return { status: 'invalid', problems: page.errors };
  const d = page.data;
  const problems = [];
  for (const rel of d.files || []) { const r = resolveFile(loc.root, rel); if (r.problem) problems.push(r.problem); }
  if (d.tc) { const r = resolveFile(loc.root, d.tc); if (r.problem) problems.push(`tc ${r.problem}`); }
  for (const k of ['links_to', 'screens']) {
    for (const s of d[k] || []) {
      const target = bySlug.get(s);
      if (!target || target.dirKind !== 'screen') problems.push(`${k}: no screen page ${s}`);
    }
  }
  if (problems.length) return { status: 'broken', problems };
  if (!d.source_hash) return { status: 'unstamped', problems: ['no source_hash — run wiki.js stamp'] };
  if (sourceHash(loc.root, d.files || []) !== d.source_hash) return { status: 'stale', problems: ['source files changed since the last stamp'] };
  return { status: 'ok', problems: [] };
}

function survey(loc) {
  const pages = loadPages(loc);
  const bySlug = new Map(pages.filter(p => !p.errors.length).map(p => [p.slug, p]));
  for (const p of pages) Object.assign(p, statusOf(loc, p, bySlug));
  return pages;
}

// ── writes (inside docs/wiki only) ───────────────────────────────────────

function writeInWiki(loc, file, content) {
  const real = path.resolve(file);
  if (!real.startsWith(loc.wiki + path.sep) || !real.endsWith('.md')) throw new Refused(`refusing to write ${file}`);
  if (isLink(real)) throw new Refused(`${path.relative(loc.root, real)} must not be a symlink`);
  const tmp = `${real}.${crypto.randomBytes(6).toString('hex')}.tmp`;
  fs.writeFileSync(tmp, content, { mode: 0o644, flag: 'wx' });
  fs.renameSync(tmp, real);
}

function stampText(text, hash, at) {
  const fm = parseFrontmatter(text);
  const lines = fm.lines.slice();
  const values = { source_hash: hash, stamped_at: at };
  const done = new Set();
  for (let i = 1; i < fm.fmEnd; i++) {
    const m = /^([a-z_]+):/.exec(lines[i]);
    if (m && STAMP_KEYS.includes(m[1])) { lines[i] = `${m[1]}: ${values[m[1]]}`; done.add(m[1]); }
  }
  const add = STAMP_KEYS.filter(k => !done.has(k)).map(k => `${k}: ${values[k]}`);
  lines.splice(fm.fmEnd, 0, ...add);
  return lines.join('\n');
}

// ── commands ─────────────────────────────────────────────────────────────

function needWiki(loc) {
  if (!loc.exists) throw new Refused('no docs/wiki in this project — create it with /wiki init');
}

function check(loc) {
  const pages = survey(loc);
  const out = Object.create(null);
  const counts = Object.fromEntries(ORDER.map(s => [s, 0]));
  for (const p of pages) {
    out[p.slug] = { status: p.status, kind: p.dirKind, path: p.rel, problems: p.problems };
    counts[p.status]++;
  }
  return { wiki: loc.exists, pages: out, counts };
}

function stamp(loc, slugs, all) {
  needWiki(loc);
  const pages = survey(loc);
  const targets = all ? pages : slugs.map(s => {
    const p = pages.find(x => x.slug === s);
    if (!p) throw new Refused(`no page ${s}`);
    return p;
  });
  if (!targets.length) throw new Refused('give the slugs to stamp, or --all');
  // check everything first, write afterwards: a refused stamp changes no page
  const plan = targets.map(p => {
    if (p.errors.length) throw new Refused(`${p.slug} is invalid: ${p.errors.join('; ')}`);
    return { p, hash: sourceHash(loc.root, p.data.files || []) };
  });
  const at = new Date().toISOString();
  for (const { p, hash } of plan) writeInWiki(loc, p.file, stampText(fs.readFileSync(p.file, 'utf8'), hash, at));
  return { stamped: plan.map(({ p, hash }) => ({ slug: p.slug, source_hash: hash })), stamped_at: at };
}

const cell = v => String(Array.isArray(v) ? v.join(', ') : v === undefined ? '' : v).replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');

function index(loc) {
  needWiki(loc);
  const pages = survey(loc);
  const screens = pages.filter(p => p.dirKind === 'screen');
  const features = pages.filter(p => p.dirKind === 'feature');
  const link = p => `[${cell(p.slug)}](${path.relative(loc.wiki, p.file).split(path.sep).join('/')})`;
  const out = [INDEX_HEADER, '', '# Wiki index', '', '## Screens', ''];
  if (screens.length) {
    out.push('| slug | title | route | status |', '|---|---|---|---|');
    for (const p of screens) out.push(`| ${link(p)} | ${cell(p.data.title)} | ${cell(p.data.route)} | ${p.status} |`);
  } else out.push('(none)');
  out.push('', '## Features', '');
  if (features.length) {
    out.push('| slug | title | screens | status |', '|---|---|---|---|');
    for (const p of features) out.push(`| ${link(p)} | ${cell(p.data.title)} | ${cell(p.data.screens)} | ${p.status} |`);
  } else out.push('(none)');
  out.push('');
  writeInWiki(loc, path.join(loc.wiki, 'index.md'), out.join('\n'));
  return { index: path.relative(loc.root, path.join(loc.wiki, 'index.md')), screens: screens.length, features: features.length };
}

function find(loc, term) {
  const q = String(term || '').trim().toLowerCase();
  if (!q) throw new Refused('give a search term');
  const results = [];
  for (const p of survey(loc)) {
    const matched = FIND_FIELDS.filter(f => {
      const v = f === 'slug' ? p.slug : p.data[f];
      return (Array.isArray(v) ? v : v === undefined ? [] : [v]).some(x => String(x).toLowerCase().includes(q));
    });
    if (matched.length) results.push({ slug: p.slug, kind: p.dirKind, title: p.data.title || '', path: p.rel, status: p.status, matched });
  }
  return { wiki: loc.exists, term: q, results };
}

// ── CLI ──────────────────────────────────────────────────────────────────

const USAGE = 'usage: node wiki.js check [--json] [--strict] | stamp <slug>… | stamp --all | index | find <term> [--json]   (all take [--root <dir>])';

function main(argv) {
  const [cmd, ...rest] = argv;
  let parsed;
  try { parsed = parseArgs(rest, { values: ['--root'], flags: ['--json', '--strict', '--all'] }); } catch (e) { console.error(`wiki: ${e.message}\n${USAGE}`); return 2; }
  const { opts, positional } = parsed;
  try {
    const loc = locate(opts['--root']);
    if (cmd === 'check') {
      if (positional.length) throw new Refused('check takes no arguments');
      const r = check(loc);
      if (opts['--json']) console.log(JSON.stringify(r));
      else if (!r.wiki) console.log('wiki: no docs/wiki in this project (create it with /wiki init)');
      else {
        for (const [slug, p] of Object.entries(r.pages)) console.log(`${p.status.padEnd(9)} ${p.kind.padEnd(7)} ${slug}${p.problems.length ? `  — ${p.problems.join('; ')}` : ''}`);
        console.log(`wiki: ${Object.entries(r.counts).map(([k, v]) => `${v} ${k}`).join(', ')}`);
      }
      return opts['--strict'] && Object.values(r.pages).some(p => p.status !== 'ok') ? 1 : 0;
    }
    if (cmd === 'stamp') {
      if (opts['--all'] && positional.length) throw new Refused('give slugs or --all, not both');
      const r = stamp(loc, positional, opts['--all']);
      console.log(JSON.stringify(r));
      return 0;
    }
    if (cmd === 'index') {
      if (positional.length) throw new Refused('index takes no arguments');
      console.log(JSON.stringify(index(loc)));
      return 0;
    }
    if (cmd === 'find') {
      if (positional.length !== 1) throw new Refused('give exactly one search term');
      const r = find(loc, positional[0]);
      if (opts['--json']) console.log(JSON.stringify(r));
      else if (!r.wiki) console.log('wiki: no docs/wiki in this project (create it with /wiki init)');
      else if (!r.results.length) console.log(`wiki: nothing matches ${JSON.stringify(r.term)}`);
      else for (const x of r.results) console.log(`${x.status.padEnd(9)} ${x.kind.padEnd(7)} ${x.slug}  ${x.path}  (${x.matched.join(', ')})`);
      return 0;
    }
    console.error(USAGE);
    return 2;
  } catch (e) {
    if (e instanceof Refused) { console.error(`wiki: ${e.message}`); return 2; }
    console.error(`wiki: ${e.stack || e.message}`);
    return 1;
  }
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { parseFrontmatter, sourceHash, check, stamp, index, find, locate, stampText, main, Refused };
